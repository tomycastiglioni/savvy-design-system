import { ChevronLeft, Link2 } from "lucide-react";
import React from "react";
import { AbsoluteFill, interpolate, interpolateColors, useCurrentFrame, useVideoConfig } from "remotion";
import { AIIcon } from "../../shared/components/AIIcon";
import { Reveal } from "../../shared/components/Reveal";
import { C, CLAMP, EASE_OUT, MOBILE, SCREEN } from "../layout";
import { MEETING, NEXT_STEPS, NUMBERS, QUICK_SUMMARY, SUMMARY_POINTS, TRANSCRIPT } from "../content";
import { T } from "../timeline";

const PAD = 16;
const HALF = (SCREEN.w - 2 * PAD) / 2;

const H: React.FC<{ readonly children: React.ReactNode }> = ({ children }) => (
  <div style={{ fontSize: 15, fontWeight: 600, color: C.ink, margin: "16px 0 6px" }}>{children}</div>
);

// Mounted at T.toNotes. Summary, then the Transcription tab, then back.
export const NotesScreen: React.FC = () => {
  const frame = useCurrentFrame();
  const { fps } = useVideoConfig();
  const t = frame / fps;

  const s1 = T.tapTranscript - T.toNotes;
  const s2 = T.tapSummary - T.toNotes;
  const tab = interpolate(t, [s1, s1 + 0.3, s2, s2 + 0.3], [0, 1, 1, 0], { ...CLAMP, easing: EASE_OUT });

  return (
    <AbsoluteFill style={{ background: C.white }}>
      {/* Nav bar */}
      <div style={{ position: "absolute", left: 0, width: SCREEN.w, top: 58, height: 36 }}>
        <div style={{ position: "absolute", left: 12, top: 8, color: C.ink }}>
          <ChevronLeft size={20} strokeWidth={2.2} />
        </div>
        <div style={{ position: "absolute", left: 0, right: 0, top: 8, textAlign: "center", fontSize: 15, fontWeight: 600, color: C.ink }}>Meeting</div>
        <div
          style={{
            position: "absolute",
            right: 14,
            top: 0,
            width: 36,
            height: 36,
            borderRadius: 18,
            background: C.white,
            boxShadow: "0 2px 10px rgba(16, 24, 40, 0.10)",
            display: "flex",
            alignItems: "center",
            justifyContent: "center",
            color: C.ink,
          }}
        >
          <Link2 size={16} strokeWidth={2} />
        </div>
      </div>

      <div style={{ position: "absolute", left: PAD, right: PAD, top: 104 }}>
        <div style={{ fontSize: 22, fontWeight: 700, color: C.ink, letterSpacing: "-0.01em" }}>{MEETING.title}</div>
        <div style={{ fontSize: 12, color: C.muted, marginTop: 7 }}>Heather Lee · {MEETING.date} at 9:32 AM</div>
        <div style={{ fontSize: 12, color: C.muted, marginTop: 4, display: "flex", alignItems: "center", gap: 5 }}>
          <AIIcon size={12} /> Generated by Savvy Intelligence
        </div>
      </div>

      {/* Tabs */}
      <div style={{ position: "absolute", left: PAD, top: MOBILE.tabsY, width: SCREEN.w - 2 * PAD, height: 34 }}>
        {["Summary", "Transcription"].map((label, i) => (
          <div
            key={label}
            style={{
              position: "absolute",
              left: i * HALF,
              width: HALF,
              top: 4,
              textAlign: "center",
              fontSize: 13.5,
              fontWeight: 600,
              color: interpolateColors(i === 0 ? tab : 1 - tab, [0, 1], [C.ink, C.faint]),
            }}
          >
            {label}
          </div>
        ))}
        <div style={{ position: "absolute", left: 0, right: 0, top: 31, height: 1, background: "#E5E6EA" }} />
        <div style={{ position: "absolute", left: tab * HALF, width: HALF, top: 30, height: 2.5, borderRadius: 2, background: C.green }} />
      </div>

      {/* Summary */}
      <div style={{ position: "absolute", left: PAD, right: PAD, top: 226, opacity: 1 - tab, translate: `${-24 * tab}px 0px` }}>
        <Reveal at={0.35} style={{ fontSize: 12.5, color: C.body }}>
          <b style={{ fontWeight: 600, color: C.ink }}>Attendees:</b> {MEETING.attendees}
        </Reveal>
        <Reveal at={0.43}>
          <H>Quick summary</H>
          <div style={{ fontSize: 13, lineHeight: 1.45, color: C.body }}>{QUICK_SUMMARY}</div>
        </Reveal>
        {SUMMARY_POINTS.map((p, i) => (
          <Reveal key={p} at={0.51 + i * 0.06} style={{ display: "flex", gap: 8, fontSize: 13, lineHeight: 1.45, color: C.body, marginTop: 4 }}>
            <span style={{ color: C.faint }}>•</span>
            {p}
          </Reveal>
        ))}
        <Reveal at={0.72}>
          <H>Decisions and next steps</H>
        </Reveal>
        {NEXT_STEPS.map((s, i) => (
          <Reveal key={s.title} at={0.78 + i * 0.06} style={{ marginBottom: 8 }}>
            <div style={{ fontSize: 12.5, fontWeight: 600, color: C.ink }}>{s.title}</div>
            <div style={{ fontSize: 11.5, color: C.muted, marginTop: 2 }}>
              Owner: {s.owner} · {s.when}
            </div>
          </Reveal>
        ))}
        <Reveal at={0.92}>
          <H>Key financial numbers</H>
          {NUMBERS.slice(0, 2).map((n) => (
            <div key={n.figure} style={{ fontSize: 12.5, color: C.body, marginBottom: 3 }}>
              <b style={{ fontWeight: 600, color: C.ink }}>{n.figure}</b> · {n.what}
            </div>
          ))}
        </Reveal>
      </div>

      {/* Transcription */}
      <div style={{ position: "absolute", left: PAD, right: PAD, top: 226, opacity: tab, translate: `${24 * (1 - tab)}px 0px` }}>
        {TRANSCRIPT.map((line, i) => {
          const p = interpolate(t, [s1 + 0.12 + i * 0.07, s1 + 0.45 + i * 0.07], [0, 1], { ...CLAMP, easing: EASE_OUT });
          return (
            <div key={line.at} style={{ marginBottom: 14, opacity: p, translate: `0px ${(1 - p) * 8}px` }}>
              <div style={{ fontSize: 12.5, fontWeight: 600, color: C.ink }}>
                {line.who} <span style={{ fontWeight: 400, color: C.faint, marginLeft: 4 }}>{line.at}</span>
              </div>
              <div style={{ fontSize: 13, lineHeight: 1.4, color: C.body, marginTop: 3 }}>{line.text}</div>
            </div>
          );
        })}
      </div>
    </AbsoluteFill>
  );
};
